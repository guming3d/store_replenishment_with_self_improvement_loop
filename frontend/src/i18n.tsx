const dictionaries: Record<Lang, Dict> = { zh, en };

const scenarioDict: Record<Lang, Record<Scenario, string>> = {
  zh: {
    standard: '标准', fresh: '短保鲜品', longtail: '长尾', new: '新品',
    promo: '促销', holiday: '节假日', season: '季节', stockout: '断货',
  },
  en: {
    standard: 'Standard', fresh: 'Short Shelf-life', longtail: 'Long-tail', new: 'New Item',
    promo: 'Promotion', holiday: 'Holiday', season: 'Seasonal', stockout: 'Stockout',
  },
};

export type TranslateFn = (key: string, vars?: Record<string, string | number>) => string;

interface I18nContextValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: TranslateFn;
  scenarioLabel: (scenario: Scenario) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

const readStoredLang = (): Lang => {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === 'en' || stored === 'zh') return stored;
  } catch {
    /* ignore storage access errors */
  }
  return 'zh';
};

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readStoredLang);

  const setLang = (next: Lang) => {
    setLangState(next);
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch {
      /* ignore storage access errors */
    }
  };

  useEffect(() => {
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
  }, [lang]);

  const value = useMemo<I18nContextValue>(() => {
    const dict = dictionaries[lang];
    const t: TranslateFn = (key, vars) => {
      let str = dict[key] ?? dictionaries.zh[key] ?? key;
      if (vars) {
        for (const [name, val] of Object.entries(vars)) {
          str = str.split(`{${name}}`).join(String(val));
        }
      }
      return str;
    };
    return {
      lang,
      setLang,
      t,
      scenarioLabel: (scenario) => scenarioDict[lang][scenario] ?? scenario,
    };
  }, [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = (): I18nContextValue => {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within LanguageProvider');
  return ctx;
};
